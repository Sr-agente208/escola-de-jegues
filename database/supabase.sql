CREATE TABLE public.turmas (
  id_turma bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome varchar(100) NOT NULL, ano_letivo smallint NOT NULL CHECK (ano_letivo > 0),
  UNIQUE (nome, ano_letivo)
);
CREATE TABLE public.professores (
  id_professor bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome varchar(150) NOT NULL, email varchar(254) NOT NULL UNIQUE
);
CREATE TABLE public.alunos (
  id_aluno bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome varchar(150) NOT NULL, matricula varchar(50) NOT NULL UNIQUE,
  email varchar(254), id_turma bigint NOT NULL REFERENCES public.turmas(id_turma)
);
CREATE TABLE public.convidados (
  id_convidado bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome varchar(150) NOT NULL, email varchar(254) NOT NULL UNIQUE,
  criado_em timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.disciplinas (
  id_disciplina bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome varchar(100) NOT NULL UNIQUE
);
CREATE TABLE public.turmas_disciplinas (
  id_turma bigint NOT NULL REFERENCES public.turmas(id_turma),
  id_disciplina bigint NOT NULL REFERENCES public.disciplinas(id_disciplina),
  id_professor bigint NOT NULL REFERENCES public.professores(id_professor),
  PRIMARY KEY (id_turma, id_disciplina)
);
CREATE TABLE public.notas (
  id_nota bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_aluno bigint NOT NULL REFERENCES public.alunos(id_aluno),
  id_disciplina bigint NOT NULL REFERENCES public.disciplinas(id_disciplina),
  id_professor bigint NOT NULL REFERENCES public.professores(id_professor),
  bimestre smallint NOT NULL CHECK (bimestre BETWEEN 1 AND 4),
  valor numeric(4,2) NOT NULL CHECK (valor BETWEEN 0 AND 10),
  atualizado_em timestamptz NOT NULL DEFAULT now(),
  UNIQUE (id_aluno, id_disciplina, bimestre)
);
CREATE FUNCTION public.atualizar_nota_data() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN NEW.atualizado_em = now(); RETURN NEW; END $$;
CREATE TRIGGER notas_atualizado BEFORE UPDATE ON public.notas
FOR EACH ROW EXECUTE FUNCTION public.atualizar_nota_data();
CREATE VIEW public.boletim WITH (security_invoker = true) AS
SELECT a.id_aluno, a.nome AS aluno, t.id_turma, t.nome AS turma, t.ano_letivo,
       d.id_disciplina, d.nome AS disciplina,
       MAX(n.valor) FILTER (WHERE n.bimestre=1) AS bimestre_1,
       MAX(n.valor) FILTER (WHERE n.bimestre=2) AS bimestre_2,
       MAX(n.valor) FILTER (WHERE n.bimestre=3) AS bimestre_3,
       MAX(n.valor) FILTER (WHERE n.bimestre=4) AS bimestre_4,
       round(avg(n.valor), 2) AS media, count(n.id_nota) AS bimestres_lancados
FROM public.alunos a JOIN public.turmas t ON t.id_turma=a.id_turma
JOIN public.notas n ON n.id_aluno=a.id_aluno
JOIN public.disciplinas d ON d.id_disciplina=n.id_disciplina
GROUP BY a.id_aluno, a.nome, t.id_turma, t.nome, t.ano_letivo, d.id_disciplina, d.nome;
ALTER TABLE public.turmas ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.professores ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.alunos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.convidados ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.disciplinas ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.turmas_disciplinas ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.notas ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.turmas, public.professores, public.alunos, public.convidados,
  public.disciplinas, public.turmas_disciplinas, public.notas, public.boletim FROM anon, authenticated;
